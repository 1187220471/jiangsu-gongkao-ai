// 格式化为提示词片段：核心考点 +2 分，重要考点 +1 分
export function formatThemesForPrompt(): string {
  const render = (themes: NewsTheme[]) =>
    themes.map((t) => `- ${t.name}：${t.keywords.join('、')}`).join('\n')
  return `【核心考点】（真题高频，命中加 2 分）\n${render(CORE_THEMES)}\n【重要考点】（真题常考，命中加 1 分）\n${render(SECONDARY_THEMES)}`
}
